def quick_intent(text):
    """Что хочет человек — по словарю: {"intent": …, "pattern" / "coin" / "term": …} или None.
    intent: explain (что такое …), coin, scan, learning, subscribe, profile, settings, autoscan,
    history, help, patterns, menu, pattern (назвал паттерн без условий)."""
    t = _norm(fix_text(text))
    if not t.strip():
        return None
    name = detect_pattern(text)
    if re.search(EXPLAIN, t):
        if name:
            return {"intent": "explain", "pattern": name}
        from guide import GLOSSARY_WORDS
        for term, patterns in GLOSSARY_WORDS.items():
            if _found(patterns, t):
                return {"intent": "explain", "term": term}
    coin = find_coin_name(text)
    if coin and not name:
        return {"intent": "coin", "coin": coin}
    for intent, patterns in INTENTS:
        if _found(patterns, t):
            return {"intent": intent}
    if name and len(_tokens(t)) <= 4:
        return {"intent": "pattern", "pattern": name}     # просто «фвг» или «ордер блок» — открыть этот паттерн
    return None
