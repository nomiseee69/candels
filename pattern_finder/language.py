def _fix_name(word):
    """Короткое слово из названия паттерна с опечаткой («флга», «кнал», «вымпл») → правильное.
    Только для названий: в длинном описании короткие слова не трогаем — слишком легко ошибиться."""
    if len(word) < 4 or word in PROTECTED or word in NAME_WORDS:
        return word
    near = [v for v in NAME_WORDS if v[0] == word[0] and abs(len(v) - len(word)) <= 1
            and _typos(word, v) <= (1 if len(v) <= 6 else 2)]
    return near[0] if len(near) == 1 else word


def detect_pattern(text):
    """Какой паттерн упомянут в тексте (по словарю) или None. Понимает сленг, английские названия,
    опечатки и текст в чужой раскладке."""
    t = _norm(fix_text(text))
    for attempt in (t, re.sub(r"[а-я]+", lambda m: _fix_name(m.group(0)), t)):
        for name, patterns in PATTERN_WORDS.items():
            if _found(patterns, attempt):
                return name
    return None


