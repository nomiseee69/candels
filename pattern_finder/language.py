def _russian_word(word):
    """Знакомое ли это русское слово (для решения «текст набран не в той раскладке»)."""
    word = word.strip(",.")
    return len(word) >= 3 and re.fullmatch(r"[а-я]+", word) is not None \
        and (word in SLANG or _known(word) or fix_word(word) != word)


def fix_layout(text):
    """Слова, набранные в английской раскладке («adu yf 4x» = «фвг на 4ч»), — обратно в русские.
    Слово переводим, только если по-английски это не термин («fvg», «ob»), а по-русски — знакомое слово;
    короткие («yf» = «на», «c» = «с») — заодно, если рядом нашлись такие слова."""
    if not re.search(r"[a-z]", text):
        return text
    pieces = re.split(r"(\s+)", text)
    keys = r"[a-z;',.\[\]`]+[?/]?"
    turn = lambda p: p.translate(TO_RUSSIAN)
    sure = set()
    for i, piece in enumerate(pieces):
        word = piece.rstrip("?/")
        if re.fullmatch(keys, piece) and word not in LATIN_TERMS and _russian_word(turn(word)):
            sure.add(i)
    if not sure:
        return text
    for i, piece in enumerate(pieces):
        word = piece.rstrip("?/")
        small = re.fullmatch(keys, piece) and word not in LATIN_TERMS and len(word) <= 3 \
            and (turn(word).strip(",.") in SMALL_WORDS or turn(word).strip(",.") in SLANG)
        timeframe = re.fullmatch(r"\d+[xlyh][?/]?", piece)          # «4x» = «4ч», «1l» = «1д»
        if i in sure or small:
            pieces[i] = turn(piece)
        elif timeframe:
            pieces[i] = piece.replace("x", "ч").replace("l", "д").replace("y", "н").translate({ord("?"): ",", ord("/"): "."})
    return "".join(pieces)


def fix_text(text):
    """Сообщение пользователя → то же, но без опечаток и с исправленной раскладкой (для разбора)."""
    text = (text or "").lower().replace("ё", "е")
    # латинская буква внутри русского слова («вымпeл» с английской «e») — частая незаметная опечатка
    text = re.sub(r"[а-яa-z]+", lambda m: m.group(0).translate(HOMOGLYPHS)
                  if re.search(r"[а-я]", m.group(0)) and re.search(r"[a-z]", m.group(0)) else m.group(0), text)
    text = fix_layout(text).replace("обьем", "объем").replace("обьём", "объем")
    return re.sub(r"[а-я]+", lambda m: fix_word(m.group(0)), text)


def _norm(text):
    text = (text or "").lower().replace("ё", "е").replace("×", "x")
    return re.sub(r"\s+", " ", text)


def stem(word):
    """Основа слова: «снял», «снятие», «снимает» → «сня»/«сним» — сравниваем основы, а не формы."""
    word = re.sub(r"[^\w]", "", word)
    for ending in ENDINGS:
        if len(word) - len(ending) >= 3 and word.endswith(ending):
            return word[:-len(ending)]
    return word


def _tokens(text):
    return [w for w in re.findall(r"[\w]+", _norm(text))]


def _close(a, b):
    """Похожи ли две основы: одна — начало другой, или отличие в 1–2 буквы (опечатка)."""
    if a == b:
        return True
    if min(len(a), len(b)) >= 4 and (a.startswith(b) or b.startswith(a)):
        return True
    return min(len(a), len(b)) >= 5 and difflib.SequenceMatcher(None, a, b).ratio() >= 0.8


def phrase_score(clause_stems, phrase):
    """Насколько фраза из банка «есть» в части описания: доля её значимых слов, найденных в тексте."""
    words = [stem(w) for w in _tokens(phrase) if w not in STOP]
    if not words:
        return 0.0
    found = sum(1 for w in words if any(_close(w, s) for s in clause_stems))
    return found / len(words)


def _clauses(text):
    """Части описания: по запятым, точкам, «;», «и», «а также» — каждое условие отдельно."""
    parts = re.split(r"[,.;:!?\n]|\s+и\s+|\s+а\s+также\s+|\s+плюс\s+|\s+\+\s+|\s+а\s+не\s+", text)
    return [p.strip() for p in parts if p.strip()]


def _found(patterns, clause):
    for p in patterns:
        m = re.search(p, clause)
        if m:
            return m
    return None


def _negated(clause, position):
    """Отрицание относится к понятию, только если стоит прямо перед ним
    (между ними — лишь служебные слова: «не должно быть FVG», «без FVG»).
    «не заполнена рядом с ценой» — «не» относится к «заполнена», а не к «рядом с ценой»."""
    before = _tokens(clause[:position])
    verbs = 0
    for w in reversed(before[-4:]):
        if w in NEGATION_WORDS or w.startswith(("исключ", "никак")):
            return True
        if w in STOP or w in FILLER:
            continue
        # «не закрылся телом», «не пробил телом» — между «не» и понятием глагол: отрицание к понятию
        if verbs == 0 and re.search(r"(л|лся|лась|лось|лись|ла|ли|ет|ется|ут|ют)$", w) and len(w) >= 4:
            verbs += 1
            continue
        return False
    return False


