"""Встроенные эталоны фигур — чтобы искать паттерн, даже если своего скриншота нет.

Форма задаётся опорными точками (время 0..1, цена 0..1), как если бы трейдер нарисовал
фигуру ломаной: двойное дно — «W», двойная вершина — «M», голова и плечи — три вершины,
средняя выше. Потом ломаная растягивается до 50 точек — так же, как форма со скриншота.
"""

from shape import SHAPE_POINTS, normalize, resample

import numpy as np

POINTS = {
    "Двойное дно": [(0, 1.0), (0.25, 0.0), (0.5, 0.6), (0.75, 0.02), (1, 0.95)],
    "Двойная вершина": [(0, 0.0), (0.25, 1.0), (0.5, 0.4), (0.75, 0.98), (1, 0.05)],
    "Голова и плечи": [(0, 0.1), (0.17, 0.65), (0.33, 0.3), (0.5, 1.0), (0.67, 0.3), (0.83, 0.62), (1, 0.0)],
    "Перевёрнутая ГиП": [(0, 0.9), (0.17, 0.35), (0.33, 0.7), (0.5, 0.0), (0.67, 0.7), (0.83, 0.38), (1, 1.0)],
}


def template_shape(name, n=SHAPE_POINTS):
    """Эталонная форма паттерна (n чисел 0..1) или None, если эталона нет."""
    points = POINTS.get(name)
    if points is None:
        return None
    xs, ys = zip(*points)
    line = np.interp(np.linspace(0, 1, 200), xs, ys)
    return [float(v) for v in normalize(resample(line, n))]
